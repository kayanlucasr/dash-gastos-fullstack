CREATE TABLE accounts (
 id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 nome varchar(100) NOT NULL CHECK(length(trim(nome))>0),
 tipo varchar(20) NOT NULL CHECK(tipo IN ('available','reserve','investment')),
 created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(nome)
);
CREATE TABLE transactions (
 id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 descricao varchar(255) NOT NULL CHECK(length(trim(descricao))>0),
 valor numeric(14,2) NOT NULL CHECK(valor>0 AND valor<10000000000),
 tipo varchar(20) NOT NULL CHECK(tipo IN ('income','expense','transfer','adjustment')),
 data date NOT NULL DEFAULT (now() AT TIME ZONE 'America/Sao_Paulo')::date,
 category_id integer REFERENCES categories(id) ON DELETE RESTRICT,
 source_account_id integer,
 destination_account_id integer,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
 cancelled_at timestamptz,
 FOREIGN KEY(source_account_id) REFERENCES accounts(id) ON DELETE RESTRICT,
 FOREIGN KEY(destination_account_id) REFERENCES accounts(id) ON DELETE RESTRICT,
 CHECK(source_account_id IS DISTINCT FROM destination_account_id),
 CHECK((tipo='income' AND source_account_id IS NULL AND destination_account_id IS NOT NULL)
 OR (tipo='expense' AND source_account_id IS NOT NULL AND destination_account_id IS NULL)
 OR (tipo='transfer' AND source_account_id IS NOT NULL AND destination_account_id IS NOT NULL AND category_id IS NULL)
 OR (tipo='adjustment' AND ((source_account_id IS NULL) <> (destination_account_id IS NULL)) AND category_id IS NULL)),
 CHECK(tipo NOT IN ('income','expense') OR category_id IS NOT NULL)
);
CREATE INDEX transactions_date ON transactions(data,id) WHERE cancelled_at IS NULL;
CREATE INDEX transactions_source_date ON transactions(source_account_id,data) WHERE cancelled_at IS NULL;
CREATE INDEX transactions_destination_date ON transactions(destination_account_id,data) WHERE cancelled_at IS NULL;
CREATE TABLE investment_valuations (
 id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 account_id integer NOT NULL,
 data date NOT NULL, valor numeric(14,2) NOT NULL CHECK(valor>=0),
 created_at timestamptz NOT NULL DEFAULT now(),
 transaction_id integer UNIQUE REFERENCES transactions(id),
 FOREIGN KEY(account_id) REFERENCES accounts(id), UNIQUE(account_id,data)
);
CREATE TABLE monthly_closings (
 id integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 month date NOT NULL CHECK(extract(day FROM month)=1),
 summary jsonb NOT NULL, revision integer NOT NULL DEFAULT 1,
 closed_at timestamptz NOT NULL DEFAULT now(), UNIQUE(month)
);
CREATE TABLE monthly_category_totals (
 closing_id integer NOT NULL REFERENCES monthly_closings(id) ON DELETE CASCADE,
 category_id integer NOT NULL REFERENCES categories(id), total numeric(16,2) NOT NULL,
 PRIMARY KEY(closing_id,category_id)
);
